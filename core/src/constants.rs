//! Базовые физические константы и параметры стандарта IAPWS-IF97.
//!
//! Включает параметры критической точки воды, лимиты применимости регионов,
//! параметры приведения для безразмерных уравнений состояния и настройки итерационных решателей.

// --- Базовые физические константы IAPWS-IF97 ---

/// Удельная газовая постоянная для обычной воды, кДж/(кг·К).
pub const R: f64 = 0.461526;
/// Критическая температура, К.
pub const T_C: f64 = 647.096;
/// Критическое давление, МПа.
pub const P_C: f64 = 22.064;
/// Критическая плотность, кг/м³.
pub const RHO_C: f64 = 322.0;

// --- Границы применимости стандарта ---

/// Минимальная температура (соответствует тройной точке воды), К.
pub const T_MIN_IF97: f64 = 273.15;
/// Максимальная температура для Регионов 1 и 2, К.
pub const T_MAX_REGION1_2: f64 = 1073.15;
/// Максимальная температура для высокотемпературного Региона 5, К.
pub const T_MAX_REGION5: f64 = 2273.15;
/// Минимальное давление (соответствует тройной точке воды), МПа.
pub const P_MIN_IF97: f64 = 0.000611212;
/// Максимальное давление для стандарта в целом, МПа.
pub const P_MAX_IF97: f64 = 100.0;
/// Максимальное давление для высокотемпературного Региона 5, МПа.
pub const P_MAX_REGION5: f64 = 50.0;

// --- Специфичные константы регионов (Параметры приведения) ---

/// Приведенное давление для Региона 1, МПа.
pub const REGION1_P_STAR: f64 = 16.53;
/// Приведенная температура для Региона 1, К.
pub const REGION1_T_STAR: f64 = 1386.0;

/// Приведенное давление для Региона 2, МПа.
pub const REGION2_P_STAR: f64 = 1.0;
/// Приведенная температура для Региона 2, К.
pub const REGION2_T_STAR: f64 = 540.0;

/// Приведенное давление для Региона 5, МПа.
pub const REGION5_P_STAR: f64 = 1.0;
/// Приведенная температура для Региона 5, К.
pub const REGION5_T_STAR: f64 = 1000.0;

// --- Настройки итерационных решателей ---

/// Стандартный допуск (tolerance) для остановки итераций (абсолютная погрешность функции).
pub const SOLVER_TOLERANCE: f64 = 1e-7;
/// Жесткий допуск для чувствительных решателей (например, поиск плотности в Регионе 3).
pub const SOLVER_TOLERANCE_TIGHT: f64 = 1e-8;
/// Допуск для проверки вырожденности матрицы Якоби (защита от деления на ноль).
pub const SOLVER_DET_TOLERANCE: f64 = 1e-12;
/// Максимальное количество итераций для одномерных решателей (Ньютон-Рафсон).
pub const SOLVER_MAX_ITER_1D: i32 = 20;
/// Максимальное количество итераций для двумерных решателей.
pub const SOLVER_MAX_ITER_2D: i32 = 50;
/// Максимальное количество итераций для поиска плотности в Регионе 3.
pub const SOLVER_MAX_ITER_DENSITY: i32 = 100;