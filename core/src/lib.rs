//! # `if97_core`
//!
//! Вычислительное ядро проекта `if97_calculator`, реализующее стандарт IAPWS-IF97
//! для воды и водяного пара.
//!
//! ## Архитектура
//!
//! В текущей редакции ядро разделено на несколько слоев:
//!
//! - `domain` — типы предметной области: ошибки, единицы измерения, состояние воды.
//! - `engine` — оркестрация вычислений: валидация, маршрутизация и запуск workflow.
//! - `regions` — низкоуровневые уравнения регионов стандарта.
//! - `topology` — фазовые границы, классификация и работа с линией насыщения.
//! - `calculator` — компактный публичный фасад `If97`, через который вызывается ядро.
//!
//! Такой разрез позволяет менять внутреннюю организацию движка, не затрагивая публичный API
//! и не вмешиваясь в математические модели и решатели.
//!
//! ## Что дает библиотека
//!
//! - строгую типизацию физических величин через модуль [`units`];
//! - автоматическое определение региона по заданным параметрам;
//! - прямые расчеты `p-T`;
//! - обратные расчеты `p-h`, `p-s`, `rho-T`;
//! - расчеты на линии насыщения `p-x`;
//! - расширенный маршрут для метастабильного пара.
//!
//! ## Пример использования
//!
//! ```rust
//! use if97_core::If97;
//! use if97_core::units::{MegaPascal, Kelvin};
//!
//! // Расчет свойств воды при давлении 3 МПа и температуре 300 К
//! let state = If97::pt(MegaPascal(3.0), Kelvin(300.0)).unwrap();
//!
//! println!("Энтальпия: {} кДж/кг", state.h.inner());
//! println!("Удельный объем: {} м³/кг", state.v.inner());
//! println!("Регион: {:?}", state.region);
//! ```

