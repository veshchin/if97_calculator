//! # Библиотека if97_core
//!
//! Высокопроизводительная реализация международного стандарта IAPWS-IF97
//! для расчета теплофизических свойств воды и водяного пара.
//!
//! Библиотека предоставляет строгую типизацию физических величин (через модуль `units`),
//! автоматическое определение региона по заданным параметрам и поддержку прямых и
//! обратных расчетов, включая итерационные решатели для околокритической зоны (Region 3).
//!
//! ## Пример использования
//!
//! ```rust
//! use if97_core::If97;
//! use if97_core::units::{MegaPascal, Kelvin};
//!
//! // Расчет свойств воды при давлении 3 МПа и температуре 300 К
//! let state = If97::pt(MegaPascal(3.0), Kelvin(300.0)).unwrap();
//!
//! println!("Энтальпия: {} кДж/кг", state.h.inner());
//! println!("Удельный объем: {} м³/кг", state.v.inner());
//! println!("Регион: {:?}", state.region);
//! ```

