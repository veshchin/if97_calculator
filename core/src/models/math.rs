/// Модуль содержит базовые математические абстракции (трейты) для расчета свойств
/// с использованием фундаментальных уравнений состояния IAPWS-IF97.

/// Трейт для регионов (1, 2, 5, 2-метастабильный), использующих безразмерную свободную энергию Гиббса ($\gamma$).
///
/// Базовое уравнение: $\gamma(\pi, \tau) = g(p, T) / (R \cdot T)$,
/// где $\pi = p / p^*$ (приведенное давление), $\tau = T^* / T$ (приведенная температура).
pub trait GibbsRegion {
    /// Базовое значение безразмерной энергии Гиббса $\gamma$.
    fn gamma(&self, pi: f64, tau: f64) -> f64;
    /// Первая производная $\gamma_{\pi}$ по приведенному давлению.
    fn gamma_pi(&self, pi: f64, tau: f64) -> f64;
    /// Первая производная $\gamma_{\tau}$ по приведенной температуре.
    fn gamma_tau(&self, pi: f64, tau: f64) -> f64;
    /// Вторая производная $\gamma_{\pi\pi}$ по приведенному давлению.
    fn gamma_pi_pi(&self, pi: f64, tau: f64) -> f64;
    /// Вторая производная $\gamma_{\tau\tau}$ по приведенной температуре.
    fn gamma_tau_tau(&self, pi: f64, tau: f64) -> f64;
    /// Смешанная производная $\gamma_{\pi\tau}$.
    fn gamma_pi_tau(&self, pi: f64, tau: f64) -> f64;
}

/// Трейт для региона 3 (околокритическая зона), использующего безразмерную свободную энергию Гельмгольца ($\phi$).
///
/// Базовое уравнение: $\phi(\delta, \tau) = f(\rho, T) / (R \cdot T)$,
/// где $\delta = \rho / \rho_c$ (приведенная плотность), $\tau = T_c / T$ (приведенная температура).
pub trait HelmholtzRegion {
    /// Базовое значение безразмерной энергии Гельмгольца $\phi$.
    fn phi(&self, delta: f64, tau: f64) -> f64;
    /// Первая производная $\phi_{\delta}$ по приведенной плотности.
    fn phi_delta(&self, delta: f64, tau: f64) -> f64;
    /// Вторая производная $\phi_{\delta\delta}$ по приведенной плотности.
    fn phi_delta_delta(&self, delta: f64, tau: f64) -> f64;
    /// Первая производная $\phi_{\tau}$ по приведенной температуре.
    fn phi_tau(&self, delta: f64, tau: f64) -> f64;
    /// Вторая производная $\phi_{\tau\tau}$ по приведенной температуре.
    fn phi_tau_tau(&self, delta: f64, tau: f64) -> f64;
    /// Смешанная производная $\phi_{\delta\tau}$.
    fn phi_delta_tau(&self, delta: f64, tau: f64) -> f64;
}