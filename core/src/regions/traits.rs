use crate::domain::errors::If97Error;
use crate::domain::state::WaterState;

/// Общий трейт для всех моделей регионов стандарта IAPWS-IF97.
///
/// Гарантирует, что каждый регион предоставляет методы для прямого расчета
/// свойств по давлению и температуре, а также опционально поддерживает
/// обратные расчеты по энтальпии или энтропии.
pub trait WaterRegionModel {
    /// Прямой расчет свойств воды/пара по давлению и температуре.
    ///
    /// # Arguments
    /// * `p` - Давление в МПа.
    /// * `t` - Температура в К.
    ///
    /// # Returns
    /// `Result<WaterState, If97Error>` с рассчитанными свойствами или ошибкой.
    fn calculate_pt(&self, p: f64, t: f64) -> Result<WaterState, If97Error>;

    /// Обратный расчет свойств по давлению и энтальпии.
    ///
    /// По умолчанию возвращает ошибку `NotImplemented`. Реализуется только для регионов,
    /// где такой расчет физически осмыслен и предусмотрен стандартом.
    fn calculate_ph(&self, _p: f64, _h: f64) -> Result<WaterState, If97Error> {
        Err(If97Error::NotImplemented(
            "Расчет по (p, h) не реализован для данного региона".into(),
        ))
    }

    /// Обратный расчет свойств по давлению и энтропии.
    ///
    /// По умолчанию возвращает ошибку `NotImplemented`. Реализуется только для регионов,
    /// где такой расчет физически осмыслен и предусмотрен стандартом.
    fn calculate_ps(&self, _p: f64, _s: f64) -> Result<WaterState, If97Error> {
        Err(If97Error::NotImplemented(
            "Расчет по (p, s) не реализован для данного региона".into(),
        ))
    }
}
