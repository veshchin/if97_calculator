// Константы из Таблицы 34 стандарта IAPWS-IF97
const N: [f64; 10] = [
    0.11670521452767e4, -0.72421316703206e6, -0.17073846940092e2,
    0.12020824702470e5, -0.32325550322333e7, 0.14915108613530e2,
    -0.48232657361591e4, 0.40511340542057e6, -0.23855557567849,
    0.65017534844798e3
];

/// Давление насыщения p_s в зависимости от температуры T (K)
pub fn saturation_pressure(t: f64) -> f64 {
    let v = t + N[8] / (t - N[9]);

    let a = v.powi(2) + N[0] * v + N[1];
    let b = N[2] * v.powi(2) + N[3] * v + N[4];
    let c = N[5] * v.powi(2) + N[6] * v + N[7];

    // Формула (30)
    let p_ratio = (2.0 * c) / (-b + (b.powi(2) - 4.0 * a * c).sqrt());
    p_ratio.powi(4) // Результат в MPa
}

/// Температура насыщения T_s в зависимости от давления p (MPa)
/// Температура насыщения T_s в зависимости от давления p (MPa)
/// Валидно для диапазона давлений: 611.213 Pa <= p <= 22.064 MPa
pub fn saturation_temperature(p: f64) -> f64 {
    // Быстрая защита границ (с микро-запасом для операций с плавающей запятой)
    // 611.213 Pa = 0.000611213 MPa
    if p < 0.000611212 || p > 22.064001 {
        return f64::NAN;
    }

    // β = p^0.25 (использование sqrt().sqrt() работает чуть быстрее powf(0.25) в некоторых LLVM)
    let beta = p.sqrt().sqrt();

    // Расчет промежуточных переменных E, F, G (Уравнение 31, Раздел 8.2)
    let beta2 = beta.powi(2);
    let e = beta2 + N[2] * beta + N[5];
    let f = N[0] * beta2 + N[3] * beta + N[6];
    let g = N[1] * beta2 + N[4] * beta + N[7];

    // Промежуточный коэффициент D
    let d = (2.0 * g) / (-f - (f.powi(2) - 4.0 * e * g).sqrt());

    // Итоговая температура насыщения T_s (Уравнение 31)
    let n9 = N[8];
    let n10 = N[9];
    let t_s = (n10 + d - ((n10 + d).powi(2) - 4.0 * (n9 + n10 * d)).sqrt()) / 2.0;

    t_s
}